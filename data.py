def validate_balance():
    """각 유형이 선택지 32개 중 정확히 8번씩 등장하는지 검증한다."""
    counts = {code: 0 for code in TYPE_CODES}
    for q in QUESTIONS:
        types = [c["type"] for c in q["choices"]]
        assert len(set(types)) == 2, f"Q{q['id']}: 두 선택지가 같은 유형"
        for t in types:
            counts[t] += 1
    assert len(QUESTIONS) == 16, "문항 수가 16개가 아님"
    assert all(v == 8 for v in counts.values()), f"유형 균형 오류: {counts}"
    return counts


validate_balance()
